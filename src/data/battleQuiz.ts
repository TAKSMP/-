//  バトルクイズ（ケースバイケースの さいてきかいを こたえる）
// -------------------------------------------------------------
//  ・ばめん（HP・じょうたい・ためている わざ など）を じっさいの
//    バトル画面で 見せて、4つの わざから いちばん いい ものを えらぶ
//  ・えらんだ わざは ほんものの バトルエンジン（resolveTurn）で
//    1ターン うごかして けっかを 見せる
//  ・せんたくしは わざライブラリ ぜんぶ（ふつう／さいきょう／'basic'）から
//  ・{me} {me2} {foe} {foe2} は じっさいの 虫の なまえに おきかわる
//
//  ◆ エンジンの きまり（もんだいを ふやす ときの ちゅうい）
//   - かくれている（もぐる など）あいてには、めいちゅうりつの ある
//     わざは あたらない。めいちゅうりつ なし（かならず あたる）わざは あたる
//   - のうりょくを さげる へんかわざは、かくれていても とどく
//   - ばいがえし（counterRatio）は ゆうせんど -3。かならず さいごに うごく
//   - とげのよろい（counterGuard）は つかった ターンだけ。こうげきを うけると はんぶん かえす
//   - さきに うごくのは ゆうせんど → すばやさ の じゅん
// =============================================================
import type { StatKey, StatusKey } from '../types'

export interface BQFighter {
  hp: number
  maxHp?: number // きほん 50
  atk?: number // きほん 5
  def?: number // きほん 5
  spd?: number // きほん じぶん6／あいて4（じぶんの ほうが はやい）
  rank?: Partial<Record<StatKey, number>>
  status?: StatusKey[]
  hide?: string // すがたを かくして ためている わざ
  charge?: string // すがたを 見せたまま ためている わざ
  recharge?: boolean // おおわざの あとで うごけない
  regen?: boolean // まいターン すこしずつ かいふく して いる
  fainted?: boolean
  moves?: string[] // あいての もっている わざ（わざコピーの もんだい用）
}

export interface BattleQuizQuestion {
  id: number
  me: BQFighter[]
  foe: BQFighter[]
  log: string[] // もんだいの まえに バトルログとして 出す
  ask?: string // きほん「{me}は どの わざを つかう？」
  options: string[] // わざID 4つ（'basic' = ふつうの こうげき）
  answer: string
  why: string // かいせつ
  foeMove?: (string | null)[] // このターン あいてが つかう わざ（ならびは foe と おなじ。きほん 'basic'、null = なにもしない）
  target?: string // じぶんの わざの あいて（'foe0' 'foe1' 'me0' 'me1'）
  copyIndex?: number // わざコピーで うつす あいての わざ
  pending?: { move: string; to: string; from: string; turnsLeft: number }
  rng?: number // さいせいで つかう さいころの め（きほん 0.3。めいちゅうが ひくい わざを はずしたい ときに 0.5 など）
}

